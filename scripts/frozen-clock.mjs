/**
 * frozen-clock.mjs — 화면을 잴 때 **시계를 한 날에 묶어 둔다.**
 *
 * ── 왜 필요한가 ────────────────────────────────────────────
 * 화면 대조 검사는 "디자인이 안 바뀌었나"를 본다. 그런데 우리 화면은 날짜를 탄다.
 * 달력은 오늘 칸에 「오늘」 을 달고, 지난 모임을 다른 자리로 옮기고,
 * 보드는 끝난 전시를 목록에서 뺀다. 그래서 **아무것도 안 고쳐도 내일이면 달라진다.**
 *
 * 실제로 재 봤다 (2026-08-22 기준으로 찍은 기준값 대비):
 *   8/23  일정 20곳 어긋남 — `.card` 2→1, 첫 카드가 바뀌면서 배경색까지 달라 보인다
 *   9/02  일정 10곳 · 보드 19곳
 *   10/01 일정 11곳 · 보드 19곳
 *
 * 이런 실패는 **거짓 경보**다. 그리고 거짓 경보가 나는 검사는 결국
 * "또 날짜 때문이겠지" 하며 `save` 를 눌러 버리게 만든다 — 그 순간 검사는 죽는다.
 * 진짜 디자인 변화도 같이 덮여 버리기 때문이다.
 *
 * ── 어떻게 ─────────────────────────────────────────────────
 * `clock.setFixedTime` 을 쓴다. `clock.install` 도 같은 화면을 내지만
 * 그쪽은 setTimeout 까지 가짜로 바꾼다. 우리 화면은 React 와 fetch 로 그려지므로
 * 타이머는 진짜인 편이 안전하다. 둘이 같은 결과를 내는 것은 확인했다.
 *
 * 옛 페이지(notice.js)도 `new Date()` 로 「오늘」 을 그린다.
 * 그래서 이식본과 옛 화면을 견줄 때도 **양쪽 다** 이 시계를 물려야
 * 남는 차이가 진짜 이식 차이가 된다.
 *
 * ── 날짜를 왜 손으로 박아 두나 ──────────────────────────────
 * 「기준을 찍는 날」로 잡으면, `save` 를 누를 때마다 기준이 다른 날을 뜻하게 된다.
 * 그러면 기준 파일이 조용히 의미를 바꾸고, 아무도 그걸 눈치채지 못한다.
 * 한 날에 박아 두고, 옮길 때는 사람이 이 값을 고치고 기준을 다시 찍게 한다.
 *
 * 이 날(2026-08-22)을 고른 이유: 그때 세 검사가 모두 통과하는 상태였다.
 * 즉 **옛 화면과 이식본이 일치한다고 확인된 날**이다.
 */

/** 화면을 잴 때 브라우저가 믿을 시각. 옮기면 기준을 다시 찍어야 한다. */
export const FROZEN_AT = '2026-08-22T10:00:00+09:00';

/** 재기 전에 부른다 — `goto` 보다 먼저여야 첫 그림부터 이 날로 그려진다. */
export async function freezeClock(page) {
  await page.clock.setFixedTime(new Date(FROZEN_AT));
}

/** 사람에게 보여 줄 짧은 날짜 — `2026-08-22` */
export const FROZEN_DAY = FROZEN_AT.slice(0, 10);
