-- 202609050001a — 9월 정기모임 식사 장소 설문의 마감을 9/14 → 9/16 으로 옮긴다
--
-- Supabase SQL Editor 에 붙여넣어 실행한다. 여러 번 실행해도 같다.
--
-- ── 왜 옮기나 ──────────────────────────────────────────────
-- 2026-09-05 기준 응답이 **한 명**이다. 총원 21명인데.
--
-- 마감이 짧아서가 아니다. 이 설문을 만든 파일(202608300003a)이 이미 적어 두었다 —
-- 「톡방에도 같은 말을 올려야 한다. 그 합의 없이 열면 지난번처럼 아무도 안 온다.」
-- **그 공지가 한 번도 안 나갔다.** 진짜 처방은 공지이고 이 파일은 안전망이다.
--
-- ── 왜 하필 9/16 인가 ──────────────────────────────────────
-- 관람일이 9/19(토) 이고 식사는 18시부터다. 열 명 안팎이 앉을 자리를 잡으려면
-- 며칠은 필요하다. 9/16(수) 21시면 예약까지 사흘이 남는다.
-- 더 미루면 응답 받을 시간은 늘지만 예약할 시간이 줄어든다 — 그 맞바꿈의 끝이 여기다.
--
-- 날짜를 바꾸려면 **아래 두 곳**을 같은 값으로 고친다 (update 의 set 과 where).
--
-- ── 되돌리기 ───────────────────────────────────────────────
-- 같은 update 를 옛 값으로 돌리면 된다. 다만 이미 마감이 지난 뒤에 되돌리면
-- 설문이 닫힌 채로 남는다 — 그때는 마감을 미래로 두는 편이 낫다.

begin;

-- **앞으로만 민다.** where 절의 부등호가 그 장치다 —
-- 누가 이미 더 뒤로 옮겨 두었다면 이 파일이 그것을 앞으로 당기지 않는다.
-- `deleted_at is null` 은 지운 설문을 되살리지 않기 위한 것이다.
update public.surveys
   set closes_at = timestamptz '2026-09-16 21:00:00+09'
 where id = '5e97b1a0-0000-4000-8000-000000000905'
   and deleted_at is null
   and closes_at < timestamptz '2026-09-16 21:00:00+09';

commit;

-- ── 확인 ───────────────────────────────────────────────────

-- 기대: 제목 「9월 정기모임 식사 장소」 · 열려있나 t · 마감 2026-09-16 21:00+09
select
  s.title                                    as 제목,
  (now() between s.opens_at and s.closes_at) as 열려있나,
  s.closes_at                                as 마감,
  s.closes_at::date - current_date           as 남은날
  from public.surveys s
 where s.id = '5e97b1a0-0000-4000-8000-000000000905';

-- 지금 몇 명이 답했나 (화면의 「N명」 과 같은 수)
select count(distinct r.id) as 응답자
  from public.survey_responses r
 where r.survey_id = '5e97b1a0-0000-4000-8000-000000000905';
