select
  s.category                                as 갈래,
  s.imported_respondents is not null        as 옮겨온것,
  (select count(*) from public.survey_options o where o.survey_id = s.id) as 후보,
  (now() between s.opens_at and s.closes_at) as 열려있나,
  s.closes_at                                as 마감
  from public.surveys s
