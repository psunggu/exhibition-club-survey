-- 202608290003a — 보드의 《서도호》 안내를 9월 정기관람 확정에 맞춘다
--
-- Supabase SQL Editor 에 붙여넣어 실행한다. 제목 기준이라 여러 번 실행해도 같다.
--
-- ── 무엇이 낡았나 (2026-08-29 확인) ───────────────────────
-- 이 줄은 8월 24일에 쓴 것이라 그때 기준으로 맞았다. 지금은 아니다.
--
--   할인   「8월 26일까지 판매, 8월 27일~9월 13일 사용」
--          → 판매는 **사흘 전에 끝났고**, 사용 회차도 9월 13일까지다.
--            정기관람은 **9월 19일**이라 얼리버드를 쓸 수 없다.
--   추천   「9월 모임 후보로 추천합니다」
--          → 후보가 아니라 **확정**이다 (2026-08-28 운영자 공지).
--   방문   2026-09-05 → 실제 관람일은 2026-09-19.
--
-- 회원이 보드를 읽고 「얼리버드로 싸게 사야지」 하고 기다리면 그냥 못 산다.
-- 지난 할인을 남겨 두는 것은 없는 것보다 나쁘다.
--
-- ── 남기는 것 ─────────────────────────────────────────────
-- 「만 24세 이하·학부생 등 증빙 시 무료」 는 **아직 유효하고**, 청년회라
-- 해당하는 회원이 있다. 맨 앞으로 올린다 — 실제로 쓸 수 있는 할인이 먼저다.
--
-- ── 안 건드리는 것 ────────────────────────────────────────
-- app/public/app.js 에는 전시실이 「3·5전시실」 로 적혀 있는데 고치지 않는다.
-- 그 파일은 배포되지 않고(vite.config.ts 의 allowlist 에 없다) 옛 화면의
-- **사본**으로만 남아 화면 대조 검사의 기준이 된다. 사본을 고치면 기준이 아니게 된다.
-- 회원이 보는 값은 여기 public.events 에 있고, 전시실은 이미 맞다.

begin;

update public.events set
  -- 실제로 쓸 수 있는 할인을 앞에 둔다. 지난 얼리버드는 「끝났다」 고 분명히 적는다.
  discount = '만 24세 이하·만 65세 이상·학부생 등은 증빙 시 무료. 다자녀카드 20%, 예술인패스 50%. '
    || '20% 얼리버드(6,400원)는 8월 26일 판매가 끝났고 사용 회차도 9월 13일까지라 9월 19일 관람에는 쓸 수 없습니다. '
    || '카드·통신사 제휴 할인 공지 없음',

  -- 「추천합니다」 가 아니라 「정해졌습니다」 다. 회원이 할 일(예매)을 함께 적는다.
  recommendation = '9월 정기관람으로 확정된 전시입니다 — 9월 19일(토) 16:50 집결, 17~18시 관람. '
    || '수·토만 21시까지 여는 야간개장이라 이 시간표가 가능합니다. '
    || '티켓은 각자 예매해야 하며 9월 7일(월) 오후 6시에 열립니다. 관람료 8,000원.',

  visit_date = date '2026-09-19',
  updated_at = now(),
  verification_note = '공식 전시 상세·예매 페이지에서 2026년 8월 29일 재확인: '
    || '기간 2026-08-27~2027-02-09, 관람료 8,000원, 전시실 지하 1층 3·4·5실과 2층 MMCA 스튜디오, '
    || '수·토 21시까지 야간개장. 얼리버드는 8월 26일 판매 종료(사용 9월 13일까지)라 9월 19일 관람에 쓸 수 없음을 반영. '
    || '운영자 확정 공지(2026-08-28)에 따라 방문 예정일을 9월 19일로 고치고 추천 문구를 확정 안내로 바꿈'
where title = '《서도호》';

commit;

-- ── 확인 ───────────────────────────────────────────────────
-- 기대: 방문 2026-09-19 · 추천문구가 「확정」 으로 시작 · 할인 앞머리가 「만 24세 이하」
select
  visit_date                                   as 방문예정,
  left(recommendation, 24)                     as 추천_앞부분,
  left(discount, 18)                           as 할인_앞부분,
  recommendation like '%얼리버드로%'            as 지난할인_권유_남음
  from public.events
 where title = '《서도호》';
