-- 202608300001a — 운영 설문 「9월부터 이런 걸 해볼까요」 를 회원 화면에서 감춘다
--
-- Supabase SQL Editor 에 붙여넣어 실행한다. id 기준이라 여러 번 실행해도 같다.
--
-- ── 왜 ────────────────────────────────────────────────────
-- 이 설문의 열 가지 후보는 **운영진 사이에서 아직 합의되지 않았다.**
-- 같은 이유로 회원용 결과 페이지(survey-result.html)의 세 절도 같은 날 가렸다 —
-- 「그래서 이렇게 바꿉니다」(#94), 「9월부터 이런 방향으로」·「비용과 거리」(#97).
--
-- 회원에게 고르라고 내놓는 것은 그 열 가지를 **하기로 했다는 뜻**으로 읽힌다.
-- 「해보고 싶은 것을 모두 골라 주세요」 라고 적어 두어도 마찬가지다.
-- 운영진이 무엇을 물을지 먼저 정한 뒤에 다시 연다.
--
-- ── 지우지 않는다 ─────────────────────────────────────────
-- `deleted_at` 만 찍는 **soft delete** 다. 설문 행도, 후보 열 개도,
-- 이미 들어온 응답이 있다면 그것도 **그대로 남는다.**
-- 화면에서만 안 보인다 — RLS 정책과 목록 질의가 모두 `deleted_at is null` 로 거른다
-- (202608200001a 의 surveys_read, app/src/lib/survey.ts 의 목록 질의).
--
-- 운영자 화면(#/survey/admin)의 「지우기」 단추가 부르는 survey_admin_delete 와
-- **같은 일**을 한다. 여기 파일로 남기는 것은 왜 감췄는지가 저장소에 남아야 하기 때문이다.
--
-- ── 함께 사라지는 것 ──────────────────────────────────────
-- 일정 화면(#/calendar) 위쪽의 「운영·요청 · 진행 중 9/8(화)까지」 줄도 같이 없어진다.
-- 그 줄은 이 설문을 DB 에서 읽어 그리므로 따로 고칠 것이 없다.

begin;

update public.surveys
   set deleted_at = now(),
       updated_at = now()
 where id = '5e97b1a0-0000-4000-8000-000000000906'
   and deleted_at is null;

commit;

-- ── 확인 ───────────────────────────────────────────────────
-- 기대: 감춘설문 에 1행(deleted_at 이 찍힘) · 회원에게_보이는_설문 에 이 설문이 없음
select id, title, deleted_at
  from public.surveys
 where id = '5e97b1a0-0000-4000-8000-000000000906';

select count(*) as 회원에게_보이는_설문
  from public.surveys
 where deleted_at is null;

-- 후보 열 개가 그대로 있는지 (감췄을 뿐 지운 것이 아니다)
select count(*) as 남아있는_후보
  from public.survey_options
 where survey_id = '5e97b1a0-0000-4000-8000-000000000906';


