-- ⚠️ **이 파일을 그대로 실행하지 않는다.** 아래 자리표시자를 실제 암호로 바꾼 뒤
--    Supabase SQL Editor 에 붙여넣어 실행하고, **저장하지 않는다.**
--
-- 이 저장소는 공개다. 암호 원문이 커밋되면 그 순간 의미가 없어진다.
-- 그래서 이 파일에는 자리표시자만 두고, 실제 암호는 어디에도 적지 않는다.
-- (scripts/validate-repository-hygiene.mjs 가 자리표시자가 바뀐 채 커밋되면 잡는다.)
--
-- 표에는 bcrypt 해시만 들어간다. 해시에서 암호를 되돌릴 수 없고,
-- 대조는 public.survey_admin_ok() 안에서만 일어난다.
--
-- ── 정하실 것 ───────────────────────────────────────────────
-- **사람마다 다른 암호를 쓸 수 있습니다.** survey_admin_ok 은 어느 운영자의
-- 해시든 하나만 맞으면 통과하므로, 각자 다른 암호를 넣어도 셋 다 들어갑니다.
-- 그렇게 두는 편이 낫습니다 — 한 분이 그만두면 그 줄만 지우면 되고,
-- 나머지 두 분은 암호를 안 바꿔도 됩니다.
--
-- 단톡방에 적지 마시고 각자 따로 주고받으세요.
-- 바꾸고 싶으면 그 줄만 다시 한 번 돌리면 덮어씁니다.
--
-- 한 사람만 넣거나 바꿀 때는 그 줄만 남기고 나머지는 지우고 실행하면 됩니다.

-- **이름도 자리표시자다.** 처음에는 운영자 세 사람의 실명을 그대로 적어 두었다.
-- 이 저장소는 공개고, AGENTS.md 는 운영진 명단을 소스에 두지 말라고 적어 두었다.
-- 암호만 가리고 이름은 지나쳤던 것이다 — record-frozen-data.mjs 는 같은 값을
-- created_by 에서 이미 가리고 있었으니, 판단이 없었던 게 아니라 여기에 적용되지
-- 않았을 뿐이다. 실행할 때 실제 이름으로 바꿔 넣고, 바꾼 파일은 저장하지 않는다.
-- (scripts/validate-survey-schema.mjs 가 이름이 자리표시자 모양인지 검사한다.)

-- **bcrypt 비용을 10 으로 둔다.** gen_salt('bf') 의 기본값은 6이고,
-- pgcrypto 문서의 속도 표로 초당 7168회다 — 대입해 맞혀 보기에 너무 빠르다.
-- 10 이면 448회로 16배 느려진다. 더 올리지 않는 것은 survey_admin_ok 이
-- 운영자 수만큼 crypt 를 돌리고 그 함수가 anon 에게 열려 있어서다 —
-- 비용을 더 올리면 아무나 서버 CPU 를 오래 붙잡을 수 있게 된다.
--
-- **이미 저장된 해시는 그대로 6 이다.** 검증은 저장된 해시에 박힌 비용을 쓴다.
-- 아래를 다시 돌려 암호를 새로 정해야 10 이 적용된다 — 세 분 모두 해야 한다.

insert into public.survey_admins (name, password_hash)
values
  ('여기에_첫째_운영자_이름을_적는다', crypt('여기에_첫째_운영자_암호를_적는다', gen_salt('bf', 10))),
  ('여기에_둘째_운영자_이름을_적는다', crypt('여기에_둘째_운영자_암호를_적는다', gen_salt('bf', 10))),
  -- 2026-08-28 에 더한 세 번째 운영자
  ('여기에_셋째_운영자_이름을_적는다', crypt('여기에_셋째_운영자_암호를_적는다', gen_salt('bf', 10)))
on conflict (name) do update set password_hash = excluded.password_hash;

-- 확인 (기대: true)
-- 방금 정한 암호를 넣어 맞는지 본다. 확인했으면 이 줄도 지우고 나간다.
select public.survey_admin_ok('여기에_확인할_암호를_적는다') as 암호_맞음;

-- 누가 들어 있는지 (암호는 안 나온다 — 해시만 저장된다)
select name as 운영자, created_at::date as 등록일
  from public.survey_admins
 order by created_at;
