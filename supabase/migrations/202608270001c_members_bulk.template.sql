-- ⚠️ **이 파일을 그대로 실행하지 않는다.** 아래 가상 이름을 실제 명부로 바꾼 뒤
--    Supabase SQL Editor 에 붙여넣어 실행하고, **저장하지 않는다.**
--
-- 이 저장소는 공개다. 명부는 그 자체가 교인 명부라 한 번 커밋되면 되돌릴 수 없다.
-- 그래서 여기에는 가상 회원(docs/fixtures/sample-members.json)만 두고,
-- 진짜 이름은 어디에도 적지 않는다. 운영자 암호(202608200001d)와 같은 방식이다.
--
-- scripts/validate-repository-hygiene.mjs 가 추적되는 파일에서
-- `('구역번호', '이름')` 모양을 찾아 가상 명부 밖의 이름이면 잡는다.
--
-- ── 왜 이 틀이 있나 ────────────────────────────────────────
-- 운영자 화면(#/survey/admin → 회원 명부)은 **한 명씩** 넣게 돼 있다.
-- 스물아홉 명을 채우려면 스물아홉 번 적고 스물아홉 번 저장해야 한다.
-- 명부가 21명에 머물러 있는 동안 회원 절반은 설문에서
-- 「등록된 회원이 아닙니다」 를 만난다 — 그것이 지금 참여를 막는 가장 큰 벽이다.
--
-- ── 여러 번 돌려도 안전하다 ────────────────────────────────
-- `on conflict (zone, name) do nothing` 이라 이미 있는 사람은 건드리지 않는다.
-- **등록일자도 처음 것을 지킨다** — 다시 넣었다고 그 사람이 오늘 들어온 것은 아니다.
-- (운영자 화면의 survey_admin_member_save 도 같은 규칙을 쓴다.)
--
-- ── 이름 적는 법 ───────────────────────────────────────────
-- 단톡방 프로필과 **글자 그대로** 맞춘다. 설문에서 대조하는 값이라
-- 한 글자라도 다르면 그 회원은 「등록된 회원이 아닙니다」 를 본다.
--   · 구역번호는 숫자만 (함수가 숫자 아닌 것은 지운다)
--   · 이름의 앞뒤 공백은 함수가 지운다. 가운데 공백은 안 지운다
--   · 동명이인은 구역번호가 다르면 서로 다른 줄이다
--     같은 구역에 동명이인이 있으면 톡방 프로필을 먼저 구분해 달라고 한 뒤 넣는다

insert into public.survey_members (zone, name, registered_at)
values
  -- ('구역번호', '이름', 등록일)   ← 이 줄들을 실제 명부로 바꾼다
  ('4101', '김하늘',  now()),
  ('4102', '박서준',  now()),
  ('4103', '이가온',  now()),
  ('4104', '최윤슬',  now()),
  ('4105', '정다인',  now()),
  ('4106', '한도윤',  now()),
  ('4107', '오시우',  now()),
  ('4108', '임세아',  now())
on conflict (zone, name) do nothing;

-- ── 확인 ───────────────────────────────────────────────────
-- 기대: 명부_인원 이 늘어나 있고, 구역_수 가 톡방과 맞는다
select
  count(*)                       as 명부_인원,
  count(distinct zone)           as 구역_수,
  min(registered_at)::date       as 가장_먼저_등록,
  max(registered_at)::date       as 가장_나중_등록
  from public.survey_members;

-- 구역별로 몇 명인지 (운영자 화면의 도넛과 같은 값)
select zone as 구역, count(*) as 인원
  from public.survey_members
 group by zone
 order by zone;

