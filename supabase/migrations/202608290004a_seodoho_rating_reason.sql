-- 202608290004a — 《서도호》 별점 근거에서 끝난 얼리버드를 뺀다
--
-- 202608290003a 를 실행한 뒤 이것을 실행한다. 제목 기준이라 여러 번 돌려도 같다.
--
-- ── 왜 ────────────────────────────────────────────────────
-- 앞 마이그레이션(0003a)에서 할인 칸을 고쳐 「얼리버드는 8월 26일에 끝났고
-- 9월 19일 관람에는 쓸 수 없다」 고 적었다. 그런데 같은 카드 위쪽 별점 근거는
-- 아직 「20% 얼리버드 … 를 높게 평가」 라고 말한다.
--
-- **한 카드 안에서 앞뒤가 안 맞는다.** 못 쓰는 할인을 별 다섯의 근거로 들고 있으면
-- 그 별점 자체를 믿기 어려워진다. 회원이 잘못 움직일 내용은 아니지만,
-- 근거가 사실과 어긋난 채로 남아 있는 것은 고쳐 둔다.
--
-- ── 무엇으로 바꾸나 ───────────────────────────────────────
-- 얼리버드 자리에 **지금도 사실인 것**을 넣는다.
--   · 관람료 8,000원 — 공식 상세에서 확인(2026-08-29)
--   · 만 24세 이하 무료 — 할인 칸에 이미 적힌 것과 같은 근거
--   · 수·토 야간개장 — 그대로 둔다. 9월 19일 17~18시 관람이 성립하는 이유다
--
-- 별점(5)은 건드리지 않는다. 얼리버드가 없어졌다고 전시의 값이 달라지지는 않는다.

begin;

update public.events set
  rating_reason = '국립현대미술관 공식 상세의 높은 관심도, 대표 작가의 대규모 개인전, '
    || '관람료 8,000원(만 24세 이하 무료)과 수·토 야간개장을 높게 평가.',
  updated_at = now(),
  verification_note = '공식 전시 상세에서 2026년 8월 29일 재확인한 관람료 8,000원과 '
    || '수·토 21시 야간개장을 근거로 남기고, 8월 26일 판매가 끝난 20% 얼리버드는 '
    || '별점 근거에서 뺐다 — 할인 칸(202608290003a)과 같은 카드에서 어긋나 있었다'
where title = '《서도호》';

commit;

-- ── 확인 ───────────────────────────────────────────────────
-- 기대: 얼리버드_남음 false · 야간개장_남음 true · 별점 5 그대로
select
  rating                                       as 별점,
  rating_reason like '%얼리버드%'               as 얼리버드_남음,
  rating_reason like '%야간개장%'               as 야간개장_남음,
  left(rating_reason, 30)                      as 근거_앞부분
  from public.events
 where title = '《서도호》';
