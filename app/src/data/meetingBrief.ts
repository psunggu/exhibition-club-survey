import type { SurveyCategory } from '../lib/survey'

/**
 * **정기모임 한 장 요약.**
 *
 * 설문 화면 맨 위에 「이번 모임은 이렇게 정해졌습니다」 를 네 줄로 보여 준다.
 * 운영자가 정한 네 갈래 —
 *   무엇을 보나 · 언제 보나 · 언제 먹나 · 어디서 먹나
 *
 * ── 왜 탭이 아니라 줄인가 ──────────────────────────────────
 * 갈래마다 탭을 두면 아직 안 정한 갈래는 눌러도 「없습니다」 뿐이다.
 * 줄로 두면 **안 정한 것도 제자리에서 그렇다고 말한다** —
 * 「식사 장소 · 아직 안 정했습니다」. 회원이 알고 싶은 것은 그쪽이다.
 *
 * ── 글은 손으로, 숫자는 DB 에서 ────────────────────────────
 * `value` 는 손으로 적는다. 「19토_17-18관람/18-19식사」 같은 톡방 글자를
 * 사람이 읽는 문장으로 옮기는 일은 기계가 짐작할 것이 아니다.
 *
 * 대신 **숫자는 한 자도 적지 않는다.** `from` 에 설문과 후보만 적어 두면
 * 화면이 집계를 읽어 「11명 중 7명」 을 만든다.
 * 손으로 적어 두면 표가 바뀌어도 그 줄만 옛날 숫자로 남는다 —
 * 이 저장소가 여러 번 겪은 실패다.
 *
 * ── 「9월 것」 이라고 묶는 자리 ─────────────────────────────
 * 제자리는 `meetups.ts` 의 `surveyIds` 다. 모임이 확정되면 그쪽으로 옮긴다.
 * 9월 모임은 2026-08-28 에 확정됐고, `meetups.ts` 의 `september-regular` 가
 * `surveyIds` 로 두 투표(전시회·관람일정)를 이미 가리키고 있다.
 *
 * **그런데 이 파일은 아직 남아 있다.** 모임 줄은 「이 모임을 무슨 설문으로 정했나」
 * 만 말하고, 이 카드가 하는 일 — 골라진 값을 「무엇을 · 언제 · 식사」 로 풀어
 * 표 수와 함께 보여 주는 것 — 은 아직 여기서만 한다.
 * 둘을 합치는 것은 따로 할 일이다. 합치기 전까지 **두 곳이 같은 모임을 말하므로
 * 한쪽만 고치면 어긋난다** — 실제로 확정 뒤 하루 동안 어긋나 있었다.
 */
export type BriefRow = {
  /** 줄을 가리키는 이름. 검사와 key 에 쓴다 */
  key: string
  /** 왼쪽 딱지. 두 줄까지 접힌다 */
  label: string
  /** 어느 탭에서 진하게 보일지 */
  category: SurveyCategory
  /**
   * 정해진 것. **`null` 이면 아직 안 정한 것**이고,
   * 그때는 화면이 `pending` 을 대신 보여 준다. 빈 문자열로 뭉개지 않는다 —
   * 「빈 값」 과 「안 정함」 이 같아지면 화면이 잘못 말할 수 있다.
   */
  value: string | null
  /** 값 아래 작은 글씨 */
  sub?: string
  /** 날짜를 크게 보여 줄 때 (`big` 이 굵게) */
  dateChip?: { big: string; small: string }
  /** 근거가 된 설문과 후보. 숫자는 화면이 여기서 읽는다 */
  from?: { surveyId: string; optionId: string }
  /**
   * **이 줄을 지금 정하고 있는 설문.**
   *
   * `from` 과 다르다 — `from` 은 「이미 정해진 것의 근거」 이고,
   * 이쪽은 「아직 정하는 중」 이다. 그래서 후보 id 가 없다. 아직 없으니까.
   *
   * 이 값이 있으면 화면이 그 설문을 보고 스스로 말을 고른다 —
   * 열려 있으면 「투표 중 · 여기서 고르세요」, 마감되면 **1위를 그대로 채운다.**
   * 가게 이름은 후보 제목이 곧 답이라 사람이 옮겨 적을 것이 없다
   * (「19토_17-18관람/18-19식사」 처럼 풀어 써야 하는 값과 다르다).
   *
   * **설문이 아직 없어도 괜찮다.** 못 찾으면 아래 `pending` 을 그대로 보여 준다.
   */
  decidedBy?: string
  /** 아직 안 정했을 때 할 말 */
  pending?: string
}

